export const OPENMOJI_BY_ID = Object.fromEntries(
  OPENMOJI_STICKERS.map((sticker) => [sticker.id, sticker]),
);

export function getOpenMojiSticker(id) {
  return OPENMOJI_BY_ID[id] || null;
}

export function getOpenMojiSrc(sticker) {
  return sticker ? `${STICKER_ROOT}/${sticker.file}` : "";
}

export function searchOpenMoji(query, category = "all") {
  const keyword = String(query || "").trim().toLowerCase();
  return OPENMOJI_STICKERS.filter((sticker) => {
    if (category !== "all" && sticker.category !== category) return false;
    if (!keyword) return true;
    const haystack = [sticker.nameZh, sticker.nameEn, sticker.id, ...sticker.keywords].join(" ").toLowerCase();
    return haystack.includes(keyword);
  });
}
